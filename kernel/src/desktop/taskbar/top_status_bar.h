
#pragma once

#include <stdint.h>

#include "system_status.h"
#include "../graphics/image.h"

namespace Astral::Desktop::TopStatusBar {

// ============================================
// ASTRALOS TOP STATUS BAR
// ============================================
//
// This is NOT the taskbar.
//
// The taskbar lives at the bottom.
// This thing lives at the top.
//
// Apparently, explaining that to the compiler
// required six error messages and a therapist.

constexpr int32_t HEIGHT = 34;

// Network state.
//
// Currently controlled by whatever networking
// driver eventually decides to exist.
//
// Wi-Fi has not returned our calls.
inline bool online = false;
inline bool wifi = false;
inline int16_t signal = -1;

// Reset everything.
//
// Yes, even the Wi-Fi.
// Especially the Wi-Fi.
inline void initialize() {
    online = false;
    wifi = false;
    signal = -1;
}

// Called when the network stack reports a change.
//
// This does not magically create Wi-Fi drivers.
// Unfortunately, C++ is not a wizard.
inline void set_network(
    bool connected,
    bool wireless,
    int16_t strength
) {
    online = connected;
    wifi = connected && wireless;

    signal =
        strength >= 0 && strength <= 100
            ? strength
            : -1;
}

// Draw the upper status bar.
//
// Thirty-four pixels of pure administrative power.
inline void render(int32_t width) {
    if (width < 380)
        return;

    constexpr uint32_t BACKGROUND = 0x101B30;
    constexpr uint32_t BORDER = 0x374664;
    constexpr uint32_t TEXT = 0xEDF2FF;
    constexpr uint32_t MUTED = 0xA0B1CD;
    constexpr uint32_t ACCENT = 0x9C8BFF;
    constexpr uint32_t CONNECTED = 0x83E5AC;

    // Paint the roof of AstralOS.
    Image::rectangle(
        0,
        0,
        width,
        HEIGHT,
        BACKGROUND
    );

    Image::rectangle(
        0,
        HEIGHT - 1,
        width,
        1,
        BORDER
    );

    // An extremely sophisticated logo.
    // NASA has declined to comment.
    Image::rectangle(
        13,
        9,
        16,
        16,
        ACCENT
    );

    Image::text(
        37,
        13,
        "AstralOS",
        TEXT
    );

    const int32_t right = width - 12;

    // These values come from the actual
    // SystemStatus module, not random numbers
    // generated by an emotionally unstable toaster.
    const char* clock =
        SystemStatus::time_text();

    const char* battery =
        SystemStatus::battery_text();

    // Time.
    Image::text(
        right - 62,
        13,
        clock,
        TEXT
    );

    // Battery.
    Image::text(
        right - 125,
        13,
        battery,
        TEXT
    );

    // Network.
    //
    // OFFLINE means OFFLINE.
    // We are not putting fake Wi-Fi bars on
    // an OS that has never met a router.
    const char* networkLabel =
        online
            ? (wifi ? "WIFI" : "LAN")
            : "OFFLINE";

    Image::text(
        right - 205,
        13,
        networkLabel,
        online ? CONNECTED : MUTED
    );

    // Future system tray.
    //
    // Currently contains approximately
    // zero applications and unlimited ambition.
    Image::text(
        right - 270,
        13,
        "TRAY",
        MUTED
    );
}

} // namespace Astral::Desktop::TopStatusBar


#!/usr/bin/env python3

from pathlib import Path
from PIL import Image
import re

KERNEL = Path(__file__).resolve().parents[1]
ROOT = KERNEL / "assets" / "desktop"
OUTPUT = ROOT / "generated" / "desktop_assets.h"

def symbol(path: Path) -> str:
    relative = path.relative_to(ROOT).with_suffix("")
    parts = list(relative.parts)

    # Remove "icons" prefix to get names like
    # apps_files, taskbar_launcher.
    if parts and parts[0] == "icons":
        parts.pop(0)

    name = re.sub(
        r"[^a-zA-Z0-9_]",
        "_",
        "_".join(parts)
    ).lower()

    if name[0].isdigit():
        name = "_" + name

    return name

def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)

    sources = sorted(
        p for p in ROOT.rglob("*")
        if p.is_file()
        and p.suffix.lower() in (".png", ".ico")
    )

    output = [
        "// Generated by pack_desktop_assets.py",
        "// Do not edit manually.",
        "#pragma once",
        '#include "desktop/graphics/image.h"',
        "",
        "namespace Astral::Desktop::Assets {",
        ""
    ]

    seen = set()

    for path in sources:
        name = symbol(path)

        if name in seen:
            raise RuntimeError(
                f"Duplicate asset name: {name}"
            )

        seen.add(name)

        with Image.open(path) as source:
            if path.suffix.lower() == ".ico":
                sizes = source.info.get("sizes", set())
                if sizes:
                    size = max(
                        sizes,
                        key=lambda s: s[0] * s[1]
                    )
                    source = source.ico.getimage(size)

            rgba = source.convert("RGBA")

            # Wallpaper: cap at 1280x720.
            if path.parent.name == "wallpapers":
                rgba.thumbnail((1280, 720))

            width, height = rgba.size

            if width > 1920 or height > 1080:
                raise RuntimeError(
                    f"Image too large: {path}"
                )

            raw = rgba.tobytes()

        print(f"{name}: {width}x{height}")

        output.append(
            f"inline constexpr uint8_t {name}_data[] = {{"
        )

        for offset in range(0, len(raw), 32):
            segment = raw[offset:offset + 32]
            output.append(
                "    " +
                ", ".join(str(b) for b in segment) +
                ","
            )

        output += [
            "};",
            f"inline constexpr Image::Bitmap {name} = {{",
            f"    {width}u, {height}u, {name}_data",
            "};",
            ""
        ]

    output.append("}")

    OUTPUT.write_text(
        "\n".join(output) + "\n",
        encoding="utf-8"
    )

    print(f"\nPacked {len(sources)} assets")
    print(OUTPUT)

if __name__ == "__main__":
    main()
